class DatabaseConfigurationError(RuntimeError):
    pass


class DatabaseConnection:
    def __init__(self, connection, postgres=False):
        self.connection = connection
        self.postgres = postgres
        self.cursor_result = None

    def cursor(self):
        return self

    def execute(self, query, parameters=()):
        if self.postgres:
            query = query.replace('?', '%s')
            self.cursor_result = self.connection.cursor()
            self.cursor_result.execute(query, parameters)
        else:
            self.cursor_result = self.connection.execute(query, parameters)
        return self.cursor_result

    def fetchone(self):
        return self.cursor_result.fetchone()

    def fetchall(self):
        return self.cursor_result.fetchall()

    def commit(self):
        self.connection.commit()

    def close(self):
        self.connection.close()


def get_db_connection():
    if DATABASE_URL:
        import psycopg
        from psycopg.rows import dict_row

        database_url = DATABASE_URL
        if database_url.startswith('postgres://'):
            database_url = 'postgresql://' + database_url.removeprefix('postgres://')
        connection = psycopg.connect(database_url, row_factory=dict_row, connect_timeout=10)
        return DatabaseConnection(connection, postgres=True)

    if IS_PRODUCTION:
        raise DatabaseConfigurationError(
            'DATABASE_URL belum dikonfigurasi. Tambahkan connection string PostgreSQL '
            'pada environment variables deployment.'
        )
    connection = sqlite3.connect(DB_FILE, timeout=10)
    connection.row_factory = sqlite3.Row
    return DatabaseConnection(connection)


def calculate_power_w(voltage_v, current_a, power_factor=1.0):
    return voltage_v * current_a * power_factor


def calculate_consumption_kwh(power_w, elapsed_seconds):
    return power_w * elapsed_seconds / 3_600_000


def current_billing_period():
    jakarta_now = datetime.now(timezone.utc) + timedelta(hours=7)
    return jakarta_now.strftime('%Y-%m')


def init_db():
    conn = get_db_connection()
    c = conn.cursor()
    
    c.execute('''CREATE TABLE IF NOT EXISTS settings (
                    key TEXT PRIMARY KEY,
                    value TEXT NOT NULL)''')
    
    c.execute(
        "INSERT INTO settings (key, value) VALUES ('tarif', ?) ON CONFLICT (key) DO NOTHING",
        (str(DEFAULT_TARIF),)
    )
    c.execute(
        "INSERT INTO settings (key, value) VALUES ('billing_period', ?) ON CONFLICT (key) DO NOTHING",
        (current_billing_period(),)
    )

    if conn.postgres:
        c.execute('''CREATE TABLE IF NOT EXISTS kamar (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        nomor TEXT UNIQUE NOT NULL,
                        penghuni TEXT,
                        voltage_v DOUBLE PRECISION DEFAULT 0,
                        current_a DOUBLE PRECISION DEFAULT 0,
                        power_factor DOUBLE PRECISION DEFAULT 1,
                        daya_watt DOUBLE PRECISION DEFAULT 0,
                        total_kwh DOUBLE PRECISION DEFAULT 0,
                        total_biaya DOUBLE PRECISION DEFAULT 0,
                        last_reading_at DOUBLE PRECISION DEFAULT 0)''')
        existing_columns = {
            row['name'] for row in c.execute(
                "SELECT column_name AS name FROM information_schema.columns WHERE table_name='kamar'"
            ).fetchall()
        }
    else:
        c.execute('''CREATE TABLE IF NOT EXISTS kamar (
                        id INTEGER PRIMARY KEY AUTOINCREMENT,
                        nomor TEXT UNIQUE NOT NULL,
                        penghuni TEXT,
                        voltage_v REAL DEFAULT 0,
                        current_a REAL DEFAULT 0,
                        power_factor REAL DEFAULT 1,
                        daya_watt REAL DEFAULT 0,
                        total_kwh REAL DEFAULT 0,
                        total_biaya REAL DEFAULT 0,
                        last_reading_at REAL DEFAULT 0)''')
        existing_columns = {row['name'] for row in c.execute("PRAGMA table_info(kamar)").fetchall()}
    measurement_type = 'DOUBLE PRECISION' if conn.postgres else 'REAL'
    new_columns = {
        'voltage_v': f'{measurement_type} DEFAULT 0',
        'current_a': f'{measurement_type} DEFAULT 0',
        'power_factor': f'{measurement_type} DEFAULT 1',
        'last_reading_at': f'{measurement_type} DEFAULT 0',
    }
    for column, definition in new_columns.items():
        if column not in existing_columns:
            c.execute(f"ALTER TABLE kamar ADD COLUMN {column} {definition}")

    allowed_rooms = tuple(room[0] for room in ROOMS)
    placeholders = ','.join('?' for _ in allowed_rooms)
    c.execute(f"DELETE FROM kamar WHERE nomor NOT IN ({placeholders})", allowed_rooms)
    for room in ROOMS:
        c.execute(
            "INSERT INTO kamar (nomor, penghuni) VALUES (?, ?) ON CONFLICT (nomor) DO NOTHING",
            room
        )

    sensor_mode = c.execute(
        "SELECT value FROM settings WHERE key='sensor_mode_version'"
    ).fetchone()
    if sensor_mode is None:
        c.execute(
            """UPDATE kamar
               SET voltage_v=0, current_a=0, power_factor=1, daya_watt=0,
                   total_kwh=0, total_biaya=0, last_reading_at=0"""
        )
        c.execute(
            "INSERT INTO settings (key, value) VALUES ('sensor_mode_version', '1') ON CONFLICT (key) DO NOTHING"
        )
        
    conn.commit()
    conn.close()
    print(f"[DB] Database siap di: {DB_FILE}")


_database_initialized = False
_database_initialization_lock = threading.Lock()


def ensure_database_initialized():
    global _database_initialized
    if _database_initialized:
        return
    with _database_initialization_lock:
        if not _database_initialized:
            init_db()
            _database_initialized = True


def ensure_current_billing_period():
    period = current_billing_period()
    conn = get_db_connection()
    try:
        changed_period = conn.execute(
            "UPDATE settings SET value=? WHERE key='billing_period' AND value<>?",
            (period, period)
        )
        if changed_period.rowcount:
            conn.execute("UPDATE kamar SET total_kwh=0, total_biaya=0")
            conn.commit()
    finally:
        conn.close()


def auth_configuration_error():
    missing = []
    if not app.secret_key:
        missing.append('FLASK_SECRET_KEY')
    if not os.environ.get('SITE_LOGIN_PASSWORD'):
        missing.append('SITE_LOGIN_PASSWORD')
    if missing:
        return jsonify({
            'error': f'Konfigurasi login belum lengkap. Atur: {", ".join(missing)}.'
        }), 503
    return None


