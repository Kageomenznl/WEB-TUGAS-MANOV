@app.before_request
def handle_cors_preflight():
    if request.method != 'OPTIONS':
        return None
    origin = request.headers.get('Origin', '')
    if origin not in allowed_origins():
        return jsonify({'error': 'Origin tidak diizinkan.'}), 403
    return '', 204


@app.before_request
def require_site_login():
    public_paths = {
        '/api/auth/status',
        '/api/login',
        '/api/logout',
        '/api/health',
        '/api/sensor/reading',
    }
    if request.path.startswith('/api/') and request.path not in public_paths:
        configuration_error = auth_configuration_error()
        if configuration_error:
            return configuration_error
        if not session.get('site_authenticated'):
            return jsonify({'error': 'Silakan login terlebih dahulu.'}), 401
    return None


@app.after_request
def add_cors_headers(response):
    origin = request.headers.get('Origin', '')
    if origin in allowed_origins():
        response.headers['Access-Control-Allow-Origin'] = origin
        response.headers['Access-Control-Allow-Methods'] = 'GET, POST, PUT, OPTIONS'
        response.headers['Access-Control-Allow-Headers'] = 'Content-Type, X-Sensor-Key'
        response.headers['Access-Control-Allow-Credentials'] = 'true'
        response.headers['Access-Control-Max-Age'] = '600'
        response.headers.add('Vary', 'Origin')
    return response


def allowed_origins():
    origins = {
        origin.strip().rstrip('/')
        for origin in os.environ.get('ALLOWED_ORIGINS', '').split(',')
        if origin.strip()
    }
    if not IS_PRODUCTION:
        origins.update({'http://localhost:5000', 'http://127.0.0.1:5000'})
    return origins


def require_api_key(environment_variable, header_name):
    configured_key = os.environ.get(environment_variable, '')
    if not configured_key:
        if IS_PRODUCTION or environment_variable == 'ADMIN_API_KEY':
            return jsonify({'status': 'gagal', 'error': f'{environment_variable} belum dikonfigurasi.'}), 503
        return None

    supplied_key = request.headers.get(header_name, '')
    if not hmac.compare_digest(supplied_key, configured_key):
        return jsonify({'status': 'gagal', 'error': 'Kunci akses tidak valid.'}), 401
    return None


@app.route('/api/admin/verify', methods=['POST'])
def verify_admin_access():
    if not session.get('site_authenticated'):
        return jsonify({'error': 'Silakan login terlebih dahulu.'}), 401

    admin_key = os.environ.get('ADMIN_API_KEY', '')
    if not admin_key:
        return jsonify({'error': 'ADMIN_API_KEY belum dikonfigurasi di environment Vercel.'}), 503

    data = request.get_json(silent=True)
    supplied_key = data.get('password') if isinstance(data, dict) else None
    if not isinstance(supplied_key, str) or not hmac.compare_digest(supplied_key, admin_key):
        session.pop('admin_verified', None)
        return jsonify({'error': 'Sandi admin tidak valid.'}), 401

    session['admin_verified'] = True
    return jsonify({'status': 'sukses'})


