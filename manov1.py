@app.route('/api/data', methods=['GET'])
def get_data():
    ensure_database_initialized()
    ensure_current_billing_period()
    conn = get_db_connection()
    try:
        tarif = float(conn.execute("SELECT value FROM settings WHERE key='tarif'").fetchone()['value'])
        kamar_rows = conn.execute("SELECT * FROM kamar ORDER BY nomor").fetchall()

        kamar_list = []
        total_semua_watt = 0
        total_semua_kwh = 0
        total_semua_biaya = 0
        waktu_sekarang = time.time()

        for row in kamar_rows:
            k = dict(row)
            k.pop('status_hidup', None)
            k['daya_watt'] = calculate_power_w(k['voltage_v'], k['current_a'], k['power_factor'])
            k['biaya_kalkulasi'] = round(k['total_kwh'] * tarif, 2)
            k['sensor_online'] = (
                k['last_reading_at'] > 0
                and waktu_sekarang - k['last_reading_at'] <= SENSOR_ONLINE_SECONDS
            )
            if k['sensor_online']:
                total_semua_watt += k['daya_watt']
            total_semua_kwh += k['total_kwh']
            total_semua_biaya += k['biaya_kalkulasi']
            kamar_list.append(k)
    finally:
        conn.close()
    
    return jsonify({
        'tarif_per_kwh': tarif,
        'kamar': kamar_list,
        'summary': {
            'total_watt': round(total_semua_watt, 2),
            'total_kwh': round(total_semua_kwh, 4),
            'total_biaya': round(total_semua_biaya, 2)
        }
    })

@app.route('/api/sensor/reading', methods=['POST'])
def receive_sensor_reading():
    """Accept an ESP32 reading.

    Deploy instructions and an Arduino HTTPClient example are in README-DEPLOY.md.
    Post nomor, voltage_v, current_a, and optional power_factor as JSON to this
    endpoint, with the X-Sensor-Key header set to the Render SENSOR_API_KEY.
    """
    auth_error = require_api_key('SENSOR_API_KEY', 'X-Sensor-Key')
    if auth_error:
        return auth_error

    data = request.get_json(silent=True)
    if not isinstance(data, dict):
        return jsonify({'status': 'gagal', 'error': 'Kirim data dalam format JSON.'}), 400

    nomor = data.get('nomor')
    if not isinstance(nomor, str) or nomor not in {room[0] for room in ROOMS}:
        return jsonify({'status': 'gagal', 'error': 'Nomor kamar harus 01 sampai 05.'}), 400

    readings = {}
    for field, minimum, maximum in (
        ('voltage_v', 0, 1000),
        ('current_a', 0, 1000),
        ('power_factor', 0, 1),
    ):
        value = data.get(field, 1.0 if field == 'power_factor' else None)
        if isinstance(value, bool) or not isinstance(value, (int, float)):
            return jsonify({'status': 'gagal', 'error': f'{field} harus berupa angka.'}), 400
        if not math.isfinite(value) or not minimum <= value <= maximum:
            return jsonify({'status': 'gagal', 'error': f'{field} di luar rentang yang diizinkan.'}), 400
        readings[field] = float(value)

    ensure_database_initialized()
    ensure_current_billing_period()
    waktu_baca = time.time()
    conn = get_db_connection()
    try:
        room = conn.execute("SELECT * FROM kamar WHERE nomor=?", (nomor,)).fetchone()
        if room is None:
            return jsonify({'status': 'gagal', 'error': 'Kamar tidak ditemukan.'}), 404

        daya_watt = calculate_power_w(
            readings['voltage_v'], readings['current_a'], readings['power_factor']
        )
        elapsed_seconds = min(
            max(0, waktu_baca - room['last_reading_at']),
            MAX_INTEGRATION_SECONDS
        ) if room['last_reading_at'] else 0
        daya_sebelumnya = room['daya_watt'] if room['last_reading_at'] else daya_watt
        total_kwh = room['total_kwh'] + calculate_consumption_kwh(
            (daya_sebelumnya + daya_watt) / 2,
            elapsed_seconds
        )

        conn.execute(
            """UPDATE kamar
               SET voltage_v=?, current_a=?, power_factor=?, daya_watt=?,
                   total_kwh=?, last_reading_at=?
               WHERE nomor=?""",
            (
                readings['voltage_v'], readings['current_a'], readings['power_factor'],
                daya_watt, total_kwh, waktu_baca, nomor
            )
        )
        conn.commit()
    finally:
        conn.close()

    return jsonify({'status': 'sukses', 'nomor': nomor, 'daya_watt': round(daya_watt, 2)})

@app.route('/api/kamar/<nomor>/penghuni', methods=['PUT'])
def update_tenant(nomor):
    if not session.pop('admin_verified', False):
        return jsonify({'error': 'Masukkan sandi admin sebelum mengubah nama penghuni.'}), 401

    if nomor not in {room[0] for room in ROOMS}:
        return jsonify({'status': 'gagal', 'error': 'Nomor kamar harus 01 sampai 05.'}), 404

    data = request.get_json(silent=True)
    nama = data.get('penghuni') if isinstance(data, dict) else None
    if not isinstance(nama, str) or not nama.strip() or len(nama.strip()) > 80:
        return jsonify({'status': 'gagal', 'error': 'Nama penghuni wajib diisi (maksimal 80 karakter).'}), 400

    ensure_database_initialized()
    conn = get_db_connection()
    try:
        result = conn.execute(
            "UPDATE kamar SET penghuni=? WHERE nomor=?",
            (nama.strip(), nomor)
        )
        if result.rowcount == 0:
            return jsonify({'status': 'gagal', 'error': 'Kamar tidak ditemukan.'}), 404
        conn.commit()
    finally:
        conn.close()
    return jsonify({'status': 'sukses', 'nomor': nomor, 'penghuni': nama.strip()})

@app.route('/api/tarif', methods=['POST'])
def set_tarif():
    if not session.pop('admin_verified', False):
        return jsonify({'error': 'Masukkan sandi admin sebelum mengubah tarif.'}), 401

    data = request.get_json(silent=True)
    tarif_baru = data.get('tarif') if isinstance(data, dict) else None
    if isinstance(tarif_baru, (int, float)) and not isinstance(tarif_baru, bool) and math.isfinite(tarif_baru) and tarif_baru > 0:
        ensure_database_initialized()
        conn = get_db_connection()
        try:
            conn.execute("UPDATE settings SET value=? WHERE key='tarif'", (str(tarif_baru),))
            conn.commit()
        finally:
            conn.close()
        return jsonify({'status': 'sukses', 'tarif': tarif_baru})
    return jsonify({'status': 'gagal', 'error': 'Tarif harus berupa angka lebih besar dari nol.'}), 400


